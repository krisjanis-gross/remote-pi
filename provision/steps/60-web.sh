# shellcheck shell=bash
# Web app: code owned by root (the web server cannot change it), only the files the app
# needs are installed, secrets and paths live in /etc/remote-pi.
# The built app is installed for every BACKEND. The PHP code, PHP-FPM and nginx only where
# PHP runs; with BACKEND=core they are removed, and the core serves the app (step 65).

# --- the built app: /opt/remote-pi/ui --------------------------------------------
stage=$(mktemp -d)
mkdir -p "$stage/ui" "$stage/app" "$stage/site"

# 1. User interface (prebuilt Ionic app)
if [[ -d "$UI_SOURCE" ]]; then
	ui_build=$UI_SOURCE
elif [[ "$UI_SOURCE" != *://* && "$UI_SOURCE" != git@* ]]; then
	die "UI folder $UI_SOURCE not found: install with provision/deploy.sh, which builds client/, or run npm run build in client/ first"
else
	git clone --quiet --depth 1 --branch "$UI_REF" "$UI_SOURCE" "$stage/ui-src"
	ui_build="$stage/ui-src/$UI_SUBDIR"
fi
[[ -f "$ui_build/index.html" ]] || die "no index.html in UI source $ui_build"
rsync -a --exclude '.*' --exclude '*.php' "$ui_build"/ "$stage/ui"/

install -d -o root -g root -m 0755 "$INSTALL_DIR"
rsync -a --delete --chown=root:root --chmod=D0755,F0644 "$stage/ui"/ "$UI_DIR"/

# ==== The PHP backend (BACKEND=php or php+watch), down to "else" (not indented: long) ====
if uses_php; then
: "${PHP_VERSION:=$(php_version)}"
export PHP_VERSION
export PHP_SOCKET=/run/php/remote-pi.sock

# --- configuration in /etc/remote-pi -----------------------------------------
api_key=$(head -n 1 "$CONFIG_DIR/api-key")
tmp_config=$(mktemp)
API_KEY_VALUE=$api_key php -r '
$origins = preg_split("/\s+/", trim(getenv("CORS_ALLOWED_ORIGINS")), -1, PREG_SPLIT_NO_EMPTY);
$settings = array(
	"remote_pi_hardened" => true,
	"config_API_KEY" => getenv("API_KEY_VALUE"),
	"remote_pi_data_dir" => getenv("DATA_DIR") . "/",
	"remote_pi_runtime_dir" => getenv("RUNTIME_DIR") . "/",
	"remote_pi_require_clock_sync" => true,
	"remote_pi_timezone" => getenv("TIMEZONE"),
	"cors_allowed_origins" => $origins,
	"reboot_command" => "sudo -n /usr/bin/systemctl reboot",
	"shutdown_command" => "sudo -n /usr/bin/systemctl poweroff",
);
echo "<?php\n// Generated by provision/install.sh. Re-run the installer instead of editing.\n";
foreach ($settings as $name => $value) {
	echo "\$$name = " . var_export($value, true) . ";\n";
}' >"$tmp_config"
install -o root -g www-data -m 0640 "$tmp_config" "$CONFIG_DIR/app.php"
rm -f "$tmp_config"

if is_yes "$MONITOR_ENABLED"; then
	tmp_config=$(mktemp)
	php -r '
$settings = array(
	"monitor_enabled" => true,
	"monitor_url_v2" => getenv("MONITOR_URL"),
	"monitor2_node_ID" => getenv("MONITOR_NODE_ID"),
	"monitor_api_key_file" => getenv("CONFIG_DIR") . "/monitor-api-key",
	"monitor_legacy_body_key" => strtolower(getenv("MONITOR_LEGACY_BODY_KEY")) === "true",
	"monitor_state_dir" => "/run/remote-pi-monitor",
);
echo "<?php\n// Generated by provision/install.sh. Re-run the installer instead of editing.\n";
foreach ($settings as $name => $value) {
	echo "\$$name = " . var_export($value, true) . ";\n";
}' >"$tmp_config"
	install -o root -g www-data -m 0640 "$tmp_config" "$CONFIG_DIR/monitor.php"
	rm -f "$tmp_config"
else
	rm -f "$CONFIG_DIR/monitor.php"
fi

# --- application files (PHP) ---------------------------------------------------
# 2. Application code: an explicit list, nothing else from server_www is installed.
app_files=(
	bootstrap.php db_common.php db_app_data_functions.php db_sensor_log_functions.php
	functions_gpio_control.php functions_hw_sensors.php functions_monitor.php
	functions_sensors.php functions_triggers.php
	json_API_v2.php json_ha.php csv_export.php read_sensor_data.php monitor_checkin.php
)
for file in "${app_files[@]}"; do
	cp "$REPO_DIR/server_www/$file" "$stage/app/"
done
cp -r "$REPO_DIR/server_www/sqlite_db_templates" "$REPO_DIR/server_www/vendor" "$stage/app/"

# 3. Site-specific scripts
if [[ -n "$SITE_FILES_DIR" ]]; then
	for file in custom_app_config.php custom_read_sensor_data.php custom_trigger_script.php \
		custom_gpio_hook.php custom_startup_script.php; do
		if [[ -f "$SITE_FILES_DIR/$file" ]]; then cp "$SITE_FILES_DIR/$file" "$stage/site/"; fi
	done
	# An entry point of its own (see custom_local_gpio.php_template), so it sits with the app.
	if [[ -f "$SITE_FILES_DIR/local_gpio.php" ]]; then cp "$SITE_FILES_DIR/local_gpio.php" "$stage/app/"; fi
	if grep -lE 'sudo |python2|exec *\( *"python ' "$stage/site"/custom_*.php 2>/dev/null; then
		warn "the site scripts listed above still call sudo/python; the web user has no sudo rights now. Port them to functions_hw_sensors.php / pinctrl."
	fi
fi
[[ -f "$stage/site/custom_app_config.php" ]] || cp "$REPO_DIR/server_www/custom_app_config.php_template" "$stage/site/custom_app_config.php"

rsync -a --delete --chown=root:root --chmod=D0755,F0644 "$stage/app"/ "$APP_DIR"/
# Site scripts may hold legacy monitor credentials: readable by the web user only.
rsync -a --delete --chown=root:www-data --chmod=D0750,F0640 "$stage/site"/ "$SITE_DIR"/
# Layout before 2026-11: everything in one web root.
rm -rf /var/www/remote-pi

# --- PHP-FPM ---------------------------------------------------------------
fpm_dir=/etc/php/$PHP_VERSION/fpm
render "$PROVISION_DIR/files/php-fpm-pool.conf" "$fpm_dir/pool.d/remote-pi.conf"
if [[ -f "$fpm_dir/pool.d/www.conf" ]]; then mv "$fpm_dir/pool.d/www.conf" "$fpm_dir/pool.d/www.conf.disabled"; fi
render "$PROVISION_DIR/files/php.ini" "$fpm_dir/conf.d/90-remote-pi.ini"
"php-fpm$PHP_VERSION" -t
systemctl restart "php$PHP_VERSION-fpm"

# --- nginx -----------------------------------------------------------------
EXTRA_LISTEN=""
for port in $EXTRA_HTTP_PORTS; do
	[[ "$port" =~ ^[0-9]+$ ]] || die "EXTRA_HTTP_PORTS must contain port numbers"
	EXTRA_LISTEN+="listen $port;"$'\n    '
done
export EXTRA_LISTEN
render "$PROVISION_DIR/files/nginx-php.conf" /etc/nginx/snippets/remote-pi-php.conf
render "$PROVISION_DIR/files/nginx-site.conf" /etc/nginx/sites-available/remote-pi
ln -sfn /etc/nginx/sites-available/remote-pi /etc/nginx/sites-enabled/remote-pi
rm -f /etc/nginx/sites-enabled/default
nginx -t
systemctl enable nginx
systemctl reload-or-restart nginx
# ==== end of the PHP backend ====
else
	# BACKEND=core: the core serves the app and the API; PHP, nginx and their files go.
	for unit in nginx $(systemctl list-unit-files --no-legend 'php*-fpm.service' 2>/dev/null | awk '{print $1}'); do
		systemctl disable --now "$unit" 2>/dev/null || true
	done
	php_packages=$(dpkg-query -W -f='${db:Status-Status} ${Package}\n' 'php*' 'nginx*' 2>/dev/null | awk '$1 == "installed" {print $2}' | xargs)
	if [[ -n "$php_packages" ]]; then
		info "removing $php_packages"
		# shellcheck disable=SC2086 # one argument per package
		apt-get purge -y $php_packages
		apt-get autoremove -y
	fi
	rm -rf "$APP_DIR" "$SITE_DIR" /etc/nginx /etc/php /run/remote-pi-monitor
	rm -f "$CONFIG_DIR/app.php" "$CONFIG_DIR/monitor.php"
fi
rm -rf "$stage"
