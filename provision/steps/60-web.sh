# shellcheck shell=bash
# Web app: code owned by root (the web server cannot change it), only the files the app
# needs are deployed, secrets and paths live in /etc/remote-pi outside the web root.

: "${PHP_VERSION:=$(php_version)}"
export PHP_VERSION
export PHP_SOCKET=/run/php/remote-pi.sock

# Runtime directories in RAM, recreated at every boot.
write_file /etc/tmpfiles.d/remote-pi.conf <<EOF
# Managed by remote-pi provision/install.sh
d $RUNTIME_DIR 0750 www-data www-data -
d /run/remote-pi-monitor 0700 www-data www-data -
EOF
systemd-tmpfiles --create /etc/tmpfiles.d/remote-pi.conf

# --- configuration in /etc/remote-pi -----------------------------------------
install -d -o root -g www-data -m 0750 "$CONFIG_DIR"
# shellcheck disable=SC2153 # API_KEY comes from the site file
api_key=$API_KEY
generated_key=no
[[ -n "$api_key" ]] || api_key=$(php_config_value "$CONFIG_DIR/app.php" config_API_KEY)
if [[ -z "$api_key" || "$api_key" == new-key ]]; then
	api_key=$(php -r 'echo bin2hex(random_bytes(20));')
	generated_key=yes
fi
[[ ${#api_key} -ge 16 ]] || die "API_KEY must be at least 16 characters"

tmp_config=$(mktemp)
API_KEY_VALUE=$api_key php -r '
$origins = preg_split("/\s+/", trim(getenv("CORS_ALLOWED_ORIGINS")), -1, PREG_SPLIT_NO_EMPTY);
$settings = array(
	"remote_pi_hardened" => true,
	"config_API_KEY" => getenv("API_KEY_VALUE"),
	"remote_pi_data_dir" => getenv("DATA_DIR") . "/",
	"remote_pi_runtime_dir" => getenv("RUNTIME_DIR") . "/",
	"remote_pi_require_clock_sync" => true,
	"cors_allowed_origins" => $origins,
	"reboot_command" => "sudo -n /usr/bin/systemctl reboot",
	"shutdown_command" => "sudo -n /usr/bin/systemctl poweroff",
);
echo "<?php\n// Generated by provision/install.sh. Re-run the installer instead of editing.\n";
foreach ($settings as $name => $value) {
	echo "\$$name = " . var_export($value, true) . ";\n";
}' >"$tmp_config"
install -o root -g www-data -m 0640 "$tmp_config" "$CONFIG_DIR/app.php"
rm -f "$tmp_config"

if is_yes "$MONITOR_ENABLED"; then
	if [[ -n "$MONITOR_KEY_FILE" ]]; then
		install -o root -g www-data -m 0640 "$MONITOR_KEY_FILE" "$CONFIG_DIR/monitor-api-key"
	fi
	tmp_config=$(mktemp)
	php -r '
$settings = array(
	"monitor_enabled" => true,
	"monitor_url_v2" => getenv("MONITOR_URL"),
	"monitor2_node_ID" => getenv("MONITOR_NODE_ID"),
	"monitor_api_key_file" => getenv("CONFIG_DIR") . "/monitor-api-key",
	"monitor_legacy_body_key" => strtolower(getenv("MONITOR_LEGACY_BODY_KEY")) === "true",
	"monitor_state_dir" => "/run/remote-pi-monitor",
);
echo "<?php\n// Generated by provision/install.sh. Re-run the installer instead of editing.\n";
foreach ($settings as $name => $value) {
	echo "\$$name = " . var_export($value, true) . ";\n";
}' >"$tmp_config"
	install -o root -g www-data -m 0640 "$tmp_config" "$CONFIG_DIR/monitor.php"
	rm -f "$tmp_config"
else
	rm -f "$CONFIG_DIR/monitor.php"
fi

# --- assemble the web root -------------------------------------------------
stage=$(mktemp -d)

# 1. User interface (prebuilt Ionic app)
if [[ -d "$UI_SOURCE" ]]; then
	ui_dir=$UI_SOURCE
else
	git clone --quiet --depth 1 --branch "$UI_REF" "$UI_SOURCE" "$stage/ui-src"
	ui_dir="$stage/ui-src/$UI_SUBDIR"
fi
[[ -f "$ui_dir/index.html" ]] || die "no index.html in UI source $ui_dir"
mkdir -p "$stage/www"
rsync -a --exclude '.*' --exclude '*.php' "$ui_dir"/ "$stage/www"/

# 2. Application code: an explicit list, nothing else from server_www is published.
app_files=(
	bootstrap.php db_common.php db_app_data_functions.php db_sensor_log_functions.php
	functions_gpio_control.php functions_hw_sensors.php functions_monitor.php
	functions_sensors.php functions_triggers.php
	json_API_v2.php json_ha.php csv_export.php read_sensor_data.php monitor_checkin.php
)
for file in "${app_files[@]}"; do
	cp "$REPO_DIR/server_www/$file" "$stage/www/"
done
cp -r "$REPO_DIR/server_www/sqlite_db_templates" "$REPO_DIR/server_www/vendor" "$stage/www/"

# 3. Site-specific scripts
if [[ -n "$SITE_FILES_DIR" ]]; then
	for file in custom_app_config.php custom_read_sensor_data.php custom_trigger_script.php \
		custom_gpio_hook.php custom_startup_script.php local_gpio.php; do
		if [[ -f "$SITE_FILES_DIR/$file" ]]; then cp "$SITE_FILES_DIR/$file" "$stage/www/"; fi
	done
	if grep -lE 'sudo |python2|exec *\( *"python ' "$stage/www"/custom_*.php 2>/dev/null; then
		warn "the site scripts listed above still call sudo/python; the web user has no sudo rights now. Port them to functions_hw_sensors.php / pinctrl."
	fi
fi
[[ -f "$stage/www/custom_app_config.php" ]] || cp "$REPO_DIR/server_www/custom_app_config.php_template" "$stage/www/custom_app_config.php"

install -d -o root -g root -m 0755 "$WEB_ROOT"
rsync -a --delete --chown=root:root --chmod=D0755,F0644 "$stage/www"/ "$WEB_ROOT"/
# may hold legacy monitor credentials
chgrp www-data "$WEB_ROOT/custom_app_config.php" && chmod 0640 "$WEB_ROOT/custom_app_config.php"
rm -rf "$stage"

# --- PHP-FPM ---------------------------------------------------------------
fpm_dir=/etc/php/$PHP_VERSION/fpm
render "$PROVISION_DIR/files/php-fpm-pool.conf" "$fpm_dir/pool.d/remote-pi.conf"
if [[ -f "$fpm_dir/pool.d/www.conf" ]]; then mv "$fpm_dir/pool.d/www.conf" "$fpm_dir/pool.d/www.conf.disabled"; fi
render "$PROVISION_DIR/files/php.ini" "$fpm_dir/conf.d/90-remote-pi.ini"
"php-fpm$PHP_VERSION" -t
systemctl restart "php$PHP_VERSION-fpm"

# --- nginx -----------------------------------------------------------------
EXTRA_LISTEN=""
for port in $EXTRA_HTTP_PORTS; do
	[[ "$port" =~ ^[0-9]+$ ]] || die "EXTRA_HTTP_PORTS must contain port numbers"
	EXTRA_LISTEN+="listen $port;"$'\n    '
done
export EXTRA_LISTEN
render "$PROVISION_DIR/files/nginx-php.conf" /etc/nginx/snippets/remote-pi-php.conf
render "$PROVISION_DIR/files/nginx-site.conf" /etc/nginx/sites-available/remote-pi
ln -sfn /etc/nginx/sites-available/remote-pi /etc/nginx/sites-enabled/remote-pi
rm -f /etc/nginx/sites-enabled/default
nginx -t
systemctl enable nginx
systemctl reload-or-restart nginx

if [[ "$generated_key" == yes ]]; then
	log "New API key for this device (enter it in the app; stored in $CONFIG_DIR/app.php):"
	printf '    %s\n' "$api_key"
fi
