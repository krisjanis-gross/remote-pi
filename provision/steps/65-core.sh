# shellcheck shell=bash disable=SC2153 # CORE_DIR and the other paths come from install.sh
# The core (Rust + Lua, core/): the rules, GPIO, sensors, the sensor log, monitor
# check-ins and the app's API in one program, remote-pi-core.service.
#   BACKEND=php        not installed (removed if it was)
#   BACKEND=php+watch  next to PHP, watch-only: switches nothing, writes nothing, logs
#                      DIFFERS where it would act differently; read-only API on 127.0.0.1:8081
#   BACKEND=core       the device: port 80, the sensor log, the monitor

core_unit=/etc/systemd/system/remote-pi-core.service
power_units=(remote-pi-power@reboot.path remote-pi-power@poweroff.path)

if ! uses_core; then
	systemctl disable --now remote-pi-core "${power_units[@]}" 2>/dev/null || true
	rm -f "$core_unit" /etc/systemd/system/remote-pi-power@.path /etc/systemd/system/remote-pi-power@.service
	rm -rf "$CORE_DIR"
	rm -f "$CONFIG_DIR/core.toml"
	systemctl daemon-reload
	return 0
fi

# --- the program and the site's rules ------------------------------------------
install -d -o root -g root -m 0755 "$CORE_DIR"
install -o root -g root -m 0755 "$CORE_BINARY_SOURCE" "$CORE_DIR/remote-pi.new"
# Fails here, not at boot, if the binary cannot run on this Pi.
core_version=$("$CORE_DIR/remote-pi.new" --version) || die "the core binary does not run on this device ($(uname -m))"
mv "$CORE_DIR/remote-pi.new" "$CORE_DIR/remote-pi"
rsync -a --delete --chown=root:www-data --chmod=D0750,F0640 "$CORE_RULES_SOURCE"/ "$CORE_DIR/rules"/
"$CORE_DIR/remote-pi" check "$CORE_DIR/rules" || die "the site's rules do not load (see above)"
info "$core_version, rules from $CORE_RULES_SOURCE"

# --- /etc/remote-pi/core.toml ----------------------------------------------------
# Written by Python so every value is quoted correctly (the site file is plain text).
ipv6=no
if [[ -e /proc/net/if_inet6 ]]; then ipv6=yes; fi
for port in $EXTRA_HTTP_PORTS; do
	[[ "$port" =~ ^[0-9]+$ ]] || die "EXTRA_HTTP_PORTS must contain port numbers"
done
tmp_config=$(mktemp)
IPV6=$ipv6 python3 - >"$tmp_config" <<'EOF'
import json, os

def q(value):
    """A TOML string (JSON's escapes are valid TOML)."""
    if any(ord(c) < 32 for c in value):
        raise SystemExit(f"control character in setting: {value!r}")
    return json.dumps(value, ensure_ascii=False)

env = os.environ
watch = env["BACKEND"] == "php+watch"
lines = [
    "# Generated by provision/install.sh. Re-run the installer instead of editing.",
    f"runtime_dir = {q(env['RUNTIME_DIR'])}",
    f"data_dir = {q(env['DATA_DIR'])}",
    "",
    "[api]",
]
if watch:
    # nginx and PHP keep port 80; this read-only API is for comparing answers on the device.
    listen = ["127.0.0.1:8081"]
else:
    # [::] also takes IPv4 connections (Linux dual-stack).
    host = "[::]" if env["IPV6"] == "yes" else "0.0.0.0"
    listen = [f"{host}:{port}" for port in ["80"] + env.get("EXTRA_HTTP_PORTS", "").split()]
lines += [
    f"listen = [{', '.join(q(a) for a in listen)}]",
    f"key_file = {q(env['CONFIG_DIR'] + '/api-key')}",
    f"ui_dir = {q(env['UI_DIR'])}",
    f"cors_allowed_origins = [{', '.join(q(o) for o in env.get('CORS_ALLOWED_ORIGINS', '').split())}]",
    # root's remote-pi-power@ units act on these files; the core needs no sudo.
    f"reboot_command = [\"/usr/bin/touch\", {q(env['RUNTIME_DIR'] + '/reboot-request')}]",
    f"shutdown_command = [\"/usr/bin/touch\", {q(env['RUNTIME_DIR'] + '/poweroff-request')}]",
]
if not watch and env.get("MONITOR_ENABLED", "").lower() in ("yes", "true", "1"):
    lines += [
        "",
        "[monitor]",
        f"url = {q(env['MONITOR_URL'])}",
        f"node_id = {q(env['MONITOR_NODE_ID'])}",
        f"key_file = {q(env['CONFIG_DIR'] + '/monitor-api-key')}",
        f"legacy_body_key = {'true' if env.get('MONITOR_LEGACY_BODY_KEY', '').lower() == 'true' else 'false'}",
    ]
print("\n".join(lines))
EOF
install -o root -g www-data -m 0640 "$tmp_config" "$CONFIG_DIR/core.toml"
rm -f "$tmp_config"

# --- reboot and power off from the app -------------------------------------------
# The core runs with NoNewPrivileges, so no sudo: it touches /run/remote-pi/<what>-request
# and these root units act on it. Only "reboot" and "poweroff" instances are enabled.
render "$PROVISION_DIR/files/remote-pi-power@.path" /etc/systemd/system/remote-pi-power@.path
render "$PROVISION_DIR/files/remote-pi-power@.service" /etc/systemd/system/remote-pi-power@.service

# --- the service -------------------------------------------------------------------
export CORE_BIN=$CORE_DIR/remote-pi
export CORE_RULES=$CORE_DIR/rules
if [[ "$BACKEND" == php+watch ]]; then export CORE_FLAGS="--watch-only"; else export CORE_FLAGS=""; fi
render "$PROVISION_DIR/files/remote-pi-core.service" "$core_unit"
# Remove the trial unit from before provisioning installed the core (it lived in RAM).
systemctl disable --now remote-pi-core-test 2>/dev/null || true
systemctl daemon-reload
if [[ "$BACKEND" == core ]]; then
	# Only one program may drive the pins: the PHP worker goes before the core starts
	# (step 70 removes it for good).
	systemctl disable --now remote-pi-worker 2>/dev/null || true
	systemctl enable --now "${power_units[@]}"
else
	systemctl disable --now "${power_units[@]}" 2>/dev/null || true
fi
systemctl enable remote-pi-core
systemctl restart remote-pi-core
